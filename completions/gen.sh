#!/bin/bash
# completions/gen.sh: generate completions/tando.bash and completions/_tando (zsh) from the
# command list: lib/help.txt (every command, its usage lines and flags), and the "# help:" lines of
# plugins (lib/cmd-*.sh) that have no section there. Run it after adding a command;
# `completions/gen.sh --check` (run by test/lint.sh, an error there) fails when the files are stale.
#
# At completion time nothing touches the network: host names come from $TANDO_CONFIG_DIR/hosts/,
# app names from ./tando.conf and from $TANDO_CONFIG_DIR/cache/apps.* (one name per line, written
# by the client when it lists apps, if it does), and plugin commands added after generation are
# found by listing lib/cmd-*.sh next to the installed tando.
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd -P) || exit 2
check=0
[ "${1:-}" = --check ] && check=1
out=$ROOT/completions
if [ "$check" = 1 ]; then
  out=$(mktemp -d "${TMPDIR:-/tmp}/tando-comp.XXXXXX") || exit 2
  trap 'rm -rf "$out"' EXIT
fi

{
  # lib/help.txt: every command, its usage lines and flags (see the comment at its top)
  echo "@CASE"
  sed -n 's/^@@ \([a-z-]*\)$/\1/p' "$ROOT/lib/help.txt" | grep -v '^overview$'
  # each command as a plugin-style section: every " | " segment of its usage belongs to it
  awk '/^@@ / { c = $2; next } c == "" || c == "overview" { next }
       /^flags:/ { f = $0; sub(/^flags: ?/, "", f); gsub(/=/, "", f); F[c] = f; next }
       /^subs:/ { n = split(substr($0, 7), P, " "); w = ""
                  for (i = 1; i <= n; i++) { split(P[i], kv, "="); if (kv[1] != "default") w = w (w ? "|" : "") kv[1] }
                  S[c] = w; next }
       /^args:/ { next }
       /^usage: / { u = $0; sub(/^usage: tando /, "", u); gsub(/\| tando /, "| ", u); U[c] = U[c] u "\n"; next }
       D[c] == "" && NF { D[c] = $0 }
       END { for (c in U) { printf "@HELP %s\n", c; n = split(U[c], L, "\n")
               for (i = 1; i < n; i++) printf "  %s %s  %s\n", L[i], (i == 1 ? F[c] : ""), D[c]
               if (S[c] != "") printf "  %s %s\n", c, S[c] } }' \
    "$ROOT/lib/help.txt"
  for f in "$ROOT"/lib/cmd-*.sh; do
    [ -f "$f" ] || continue
    n=${f##*/cmd-}; n=${n%.sh}
    [ "$n" = logx ] && continue
    grep -q "^@@ $n\$" "$ROOT/lib/help.txt" && continue
    echo "@HELP $n"
    sed -n 's/^# help: /  /p' "$f"
  done
} | perl -e '
  my ($sec, $plugin, %cmd, @order);
  sub add {
    my $c = shift;
    push @order, $c unless $cmd{$c};
    $cmd{$c} //= { subs => [], flags => [], args => "", desc => "" };
  }
  sub uniq { my %s; grep { !$s{$_}++ } @_ }
  while (<STDIN>) {
    chomp;
    if (/^@(\w+)\s*(\S*)/) { ($sec, $plugin) = ($1, $2); add($plugin) if $plugin; next }
    if ($sec eq "CASE") { add($_) for split /\|/; next }
    # usage / help lines: segments separated by " | ", a description after two or more spaces
    s/^\s+//;
    my $desc = s/\s{2,}(\S.*)$// ? $1 : "";
    for my $seg (split /\s+\|\s+/) {
      my @w = split /\s+/, $seg;
      # in a plugin help line every segment belongs to the plugin: "enable" is "alerts enable"
      unshift @w, $plugin if $sec eq "HELP" && $w[0] ne $plugin;
      my $c = shift @w or next;
      next unless $c =~ /^[a-z][a-z-]*$/;
      add($c);
      $cmd{$c}{desc} ||= $desc;
      if (@w && $w[0] =~ /^[a-z][a-z|-]*$/) {
        my $s = shift @w;
        push @{ $cmd{$c}{subs} }, split /\|/, $s;
      }
      for my $x (@w) {
        # "<id|all>|rotate|hook": bare words after a placeholder are more subcommands
        push @{ $cmd{$c}{subs} }, split /\|/, $1 if $x =~ /^[<\[][^>\]]*[>\]]\|([a-z|-]+)$/;
        push @{ $cmd{$c}{flags} }, $1 while $x =~ /(?:^|[\[|(\s])(--?[A-Za-z0-9][A-Za-z0-9-]*)/g;
        $cmd{$c}{args} = "apps" if $x =~ /^[\[<]app[|\]>]/ && !$cmd{$c}{args};
        $cmd{$c}{args} = "hosts" if $x =~ /^[\[<]host[\]>]/ && !$cmd{$c}{args};
      }
    }
  }
  $cmd{host}{subargs} = "setup|rm|rename:hosts" if $cmd{host};
  $cmd{$_}{subs} = [uniq @{ $cmd{$_}{subs} }], $cmd{$_}{flags} = [uniq @{ $cmd{$_}{flags} }] for keys %cmd;
  for my $c (@order) {
    my $x = $cmd{$c};
    my $d = $x->{desc}; $d =~ s/[\x27"\\]//g; $d =~ s/:/ -/g;
    print join("\x1f", $c, join(" ", @{ $x->{subs} }), join(" ", @{ $x->{flags} }), $x->{args},
      $x->{subargs} // "", $d), "\n";
  }
' > "$out/.table" || exit 2

# ---- bash ---------------------------------------------------------------------------------------

{
cat <<'EOF'
# bash completion for tando. Generated by completions/gen.sh: edit that, not this file.
# COMPREPLY=($(compgen ...)) is the bash 3.2 idiom (mapfile is bash 4); words are single tokens.
# shellcheck disable=SC2207,SC2046
# bash 3.2 compatible. Install: source it from ~/.bashrc, or copy it to
# $(brew --prefix)/etc/bash_completion.d/tando (install.sh puts it in
# PREFIX/share/bash-completion/completions/tando).

_tando_cfg() { printf '%s' "${TANDO_CONFIG_DIR:-$HOME/.config/tando}"; }
_tando_hosts() {
  local f
  for f in "$(_tando_cfg)"/hosts/*; do [ -f "$f" ] && printf '%s\n' "${f##*/}"; done
}
_tando_apps() {
  local f
  [ -f tando.conf ] && sed -n 's/^[[:space:]]*app[[:space:]]*=[[:space:]]*\([a-z0-9-]*\).*/\1/p' tando.conf
  for f in "$(_tando_cfg)"/cache/apps.*; do [ -f "$f" ] && cat "$f"; done
  return 0
}
_tando_plugins() { # plugin commands next to the tando on PATH
  local self d f
  self=$(command -v tando 2> /dev/null) || return 0
  while [ -L "$self" ]; do
    d=$(readlink "$self")
    case $d in /*) self=$d;; *) self=$(dirname "$self")/$d;; esac
  done
  for f in "$(dirname "$self")"/../lib/cmd-*.sh; do
    [ -f "$f" ] || continue
    f=${f##*/cmd-}; printf '%s\n' "${f%.sh}"
  done
}
EOF
printf '_tando_commands="'
cut -d $'\x1f' -f1 "$out/.table" | tr '\n' ' ' | sed 's/ $//' | fold -s -w 96 | sed '2,$s/^/  /'
printf '"\n\n'
echo '_tando() {'
cat <<'EOF'
  local cur prev cmd w i
  cur=${COMP_WORDS[COMP_CWORD]}
  prev=${COMP_WORDS[COMP_CWORD-1]}
  COMPREPLY=()
  case $prev in
    -a) COMPREPLY=($(compgen -W "$(_tando_apps)" -- "$cur")); return 0;;
    -H) COMPREPLY=($(compgen -W "$(_tando_hosts)" -- "$cur")); return 0;;
    -n|--watch|--port) return 0;;
    --key) COMPREPLY=($(compgen -f -- "$cur")); return 0;;
  esac
  # the command is the first word that is not an option or an option's value
  cmd="" i=1
  while [ "$i" -lt "$COMP_CWORD" ]; do
    w=${COMP_WORDS[i]}
    case $w in -a|-H|-n|--watch) i=$((i + 2)); continue;; -*) ;; *) cmd=$w; break;; esac
    i=$((i + 1))
  done
  if [ -z "$cmd" ]; then
    case $cur in
      -*) COMPREPLY=($(compgen -W "-a -H -h --help" -- "$cur"));;
      *) # shellcheck disable=SC2086 # the command list is split into words on purpose
        COMPREPLY=($(compgen -W "$(printf '%s\n' $_tando_commands $(_tando_plugins) | sort -u)" -- "$cur"));;
    esac
    return 0
  fi
  local subs="" flags="" args="" sub=${COMP_WORDS[i+1]:-}
  case $cmd in
EOF
while IFS=$'\x1f' read -r c subs flags args subargs desc; do
  printf '    %s) subs="%s" flags="$flags %s" args="%s"' "$c" "$subs" "$flags" "$args"
  case $subargs in
    *:*) printf '\n      [ "$COMP_CWORD" -eq $((i + 2)) ] && case $sub in %s) args=%s;; esac' \
           "${subargs%%:*}" "${subargs#*:}";;
  esac
  printf ';;\n'
done < "$out/.table"
cat <<'EOF'
  esac
  case $cur in -*) COMPREPLY=($(compgen -W "$flags" -- "$cur")); return 0;; esac
  if [ -n "$subs" ] && [ "$COMP_CWORD" -eq $((i + 1)) ]; then
    COMPREPLY=($(compgen -W "$subs" -- "$cur"))
  elif [ "$args" = hosts ]; then COMPREPLY=($(compgen -W "$(_tando_hosts)" -- "$cur"))
  elif [ "$args" = apps ]; then COMPREPLY=($(compgen -W "$(_tando_apps)" -- "$cur"))
  fi
  return 0
}
complete -F _tando tando
EOF
} > "$out/tando.bash"

# ---- zsh ----------------------------------------------------------------------------------------

{
cat <<'EOF'
#compdef tando
# zsh completion for tando. Generated by completions/gen.sh: edit that, not this file.
# Install: put this file (named _tando) in a directory on $fpath before compinit
# (install.sh uses PREFIX/share/zsh/site-functions).

_tando_hosts() {
  local -a h
  h=(${TANDO_CONFIG_DIR:-$HOME/.config/tando}/hosts/*(N:t))
  compadd -a h
}
_tando_apps() {
  local -a a
  local d=${TANDO_CONFIG_DIR:-$HOME/.config/tando}
  [[ -f tando.conf ]] &&
    a+=(${(f)"$(sed -n 's/^[[:space:]]*app[[:space:]]*=[[:space:]]*\([a-z0-9-]*\).*/\1/p' tando.conf)"})
  a+=(${(f)"$(cat $d/cache/apps.*(N) 2> /dev/null)"})
  compadd -a a
}

_tando() {
  local -a cmds plugins
  local self=${commands[tando]}
  cmds=(
EOF
while IFS=$'\x1f' read -r c subs flags args subargs desc; do
  printf "    '%s:%s'\n" "$c" "${desc:-$c}"
done < "$out/.table"
cat <<'EOF'
  )
  if [[ -n $self ]]; then
    self=${self:A}
    plugins=(${self:h}/../lib/cmd-*.sh(N:t:r))
    plugins=(${plugins#cmd-})
  fi
  local curcontext=$curcontext state line
  _arguments -C \
    '-a[app]:app:_tando_apps' \
    '-H[host]:host:_tando_hosts' \
    '1:command:->cmd' \
    '*::arg:->args'
  case $state in
    cmd) _describe -t commands 'tando command' cmds; (( ${#plugins} )) && compadd -a plugins ;;
    args)
      local subs="" flags="" args=""
      case $line[1] in
EOF
while IFS=$'\x1f' read -r c subs flags args subargs desc; do
  printf '        %s) subs="%s" flags="%s" args="%s"' "$c" "$subs" "$flags" "$args"
  case $subargs in
    *:*) printf '\n          [[ $CURRENT -eq 3 && $words[2] == (%s) ]] && { _tando_%s; return }' \
      "${subargs%%:*}" "${subargs#*:}";;
  esac
  printf ' ;;\n'
done < "$out/.table"
cat <<'EOF'
      esac
      if [[ $PREFIX == -* ]]; then compadd -- ${=flags}
      elif [[ -n $subs && $CURRENT -eq 2 ]]; then compadd -- ${=subs}
      elif [[ $args == hosts ]]; then _tando_hosts
      elif [[ $args == apps ]]; then _tando_apps
      fi ;;
  esac
}

_tando "$@"
EOF
} > "$out/_tando"
rm -f "$out/.table"

if [ "$check" = 1 ]; then
  if cmp -s "$out/tando.bash" "$ROOT/completions/tando.bash" && cmp -s "$out/_tando" "$ROOT/completions/_tando"; then
    echo "completions: up to date"
  else
    echo "completions: out of date: run completions/gen.sh" >&2
    exit 1
  fi
else
  echo "completions: wrote completions/tando.bash and completions/_tando ($(grep -c "^    '" "$out/_tando") commands)"
fi
